const fs = require('node:fs')
const path = require('node:path')

function prepareFontEntry(preview, root) {
  const target = path.join(root, 'lib', 'build-fonts.generated.ts')
  const content = "// Generated by next.config.mjs.\n"
    + `export { siteFontClassName } from './${preview ? 'preview-fonts' : 'site-fonts'}'\n`
  let previous
  try { previous = fs.readFileSync(target, 'utf8') }
  catch (error) { if (error.code !== 'ENOENT') throw error }
  if (previous !== content) fs.writeFileSync(target, content)
}

module.exports = { prepareFontEntry }
